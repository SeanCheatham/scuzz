struct SkPaint {
  SkColor color;
  int stroke;
  float stroke_width;
  float text_size;
};

struct SkCanvas {
  struct SkSurface *surface;
};

struct SkSurface {
  int width;
  int height;
  uint8_t *pixels; /* RGBA8888 */
  SkCanvas canvas; /* borrowed via sk_surface_get_canvas */
};

SkColor sk_color_rgba(uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
  SkColor c = {r, g, b, a};
  return c;
}

SkColor sk_color_argb(uint32_t argb) {
  SkColor c;
  c.a = (uint8_t)((argb >> 24) & 0xff);
  c.r = (uint8_t)((argb >> 16) & 0xff);
  c.g = (uint8_t)((argb >> 8) & 0xff);
  c.b = (uint8_t)(argb & 0xff);
  return c;
}

SkSurface *sk_surface_make_raster_n32_premul(int width, int height) {
  SkSurface *s;
  if (width <= 0 || height <= 0)
    return NULL;
  s = (SkSurface *)calloc(1, sizeof(SkSurface));
  if (!s)
    return NULL;
  s->width = width;
  s->height = height;
  s->pixels = (uint8_t *)calloc((size_t)width * (size_t)height, 4);
  if (!s->pixels) {
    free(s);
    return NULL;
  }
  s->canvas.surface = s;
  return s;
}

void sk_surface_unref(SkSurface *surface) {
  if (!surface)
    return;
  free(surface->pixels);
  free(surface);
}

SkCanvas *sk_surface_get_canvas(SkSurface *surface) {
  return surface ? &surface->canvas : NULL;
}

int sk_surface_width(const SkSurface *surface) {
  return surface ? surface->width : 0;
}

int sk_surface_height(const SkSurface *surface) {
  return surface ? surface->height : 0;
}

const uint8_t *sk_surface_peek_pixels(const SkSurface *surface, size_t *out_size) {
  if (!surface) {
    if (out_size)
      *out_size = 0;
    return NULL;
  }
  if (out_size)
    *out_size = (size_t)surface->width * (size_t)surface->height * 4;
  return surface->pixels;
}

static void put_pixel(SkSurface *s, int x, int y, SkColor color) {
  uint8_t *p;
  if (!s || x < 0 || y < 0 || x >= s->width || y >= s->height)
    return;
  p = s->pixels + ((size_t)y * (size_t)s->width + (size_t)x) * 4;
  if (color.a == 255) {
    p[0] = color.r;
    p[1] = color.g;
    p[2] = color.b;
    p[3] = 255;
  } else if (color.a == 0) {
    return;
  } else {
    uint8_t ia = (uint8_t)(255 - color.a);
    p[0] = (uint8_t)((color.r * color.a + p[0] * ia) / 255);
    p[1] = (uint8_t)((color.g * color.a + p[1] * ia) / 255);
    p[2] = (uint8_t)((color.b * color.a + p[2] * ia) / 255);
    p[3] = 255;
  }
}

void sk_canvas_clear(SkCanvas *canvas, SkColor color) {
  int x, y;
  if (!canvas || !canvas->surface)
    return;
  for (y = 0; y < canvas->surface->height; y++)
    for (x = 0; x < canvas->surface->width; x++)
      put_pixel(canvas->surface, x, y, color);
}

void sk_canvas_draw_rect(SkCanvas *canvas, float x, float y, float w, float h,
                         const SkPaint *paint) {
  int x0, y0, x1, y1, ix, iy;
  if (!canvas || !canvas->surface || !paint || w <= 0 || h <= 0)
    return;
  x0 = (int)x;
  y0 = (int)y;
  x1 = (int)(x + w);
  y1 = (int)(y + h);
  if (paint->stroke) {
    int t = (int)(paint->stroke_width < 1.f ? 1.f : paint->stroke_width);
    for (iy = y0; iy < y1; iy++)
      for (ix = x0; ix < x1; ix++)
        if (ix < x0 + t || iy < y0 + t || ix >= x1 - t || iy >= y1 - t)
          put_pixel(canvas->surface, ix, iy, paint->color);
  } else {
    for (iy = y0; iy < y1; iy++)
      for (ix = x0; ix < x1; ix++)
        put_pixel(canvas->surface, ix, iy, paint->color);
  }
}

